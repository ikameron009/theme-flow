def category_of(name):
    if name in EXPLICIT:
        return EXPLICIT[name]
    for c in BLOCK:
        if c in name:
            return None
    for cat, kws in CAT_KEYWORDS:
        for kw in kws:
            if kw in name:
                return cat
    return None

# 集計
rows = []
for name in sorted(S):
    cat = category_of(name)
    if cat:
        rows.append((name, cat))

# カテゴリごとの件数
from collections import Counter
cnt = Counter(c for _, c in rows)
print("=== category counts ===")
for c, n in cnt.most_common():
    print(f"  {c}: {n}")
print(f"\nTOTAL pool = {len(rows)}")

# 出力(カテゴリ順→名前順)
CATORDER = [c for c, _ in CAT_KEYWORDS]
rows.sort(key=lambda r: (CATORDER.index(r[1]) if r[1] in CATORDER else 99, r[0]))
out = os.path.join(BASE, "themes_pool.csv")
with open(out, "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f)
    w.writerow(["theme", "category"])
    w.writerows(rows)
print("saved", out)
